/* بناء استخلاصي لباقي الجذاذات: المرحلي/النهائي من أهداف أنشطة الأستاذ حرفيًا،
   والمنتوج من أسطر استهلال فقرات المحتوى، والتشخيصي/الامتداد إطارات منهجية */
export function buildDevPlan(f: ImportedFiche, slotTitle: string): DevPlan {
  const objectives: string[] = [];
  const contentFirsts: string[] = [];
  for (const b of f.blocks) {
    const t = b.table;
    if (!t) continue;
    for (const r of t.rows) {
      r.forEach((c, ci) => {
        const ls = [...(c.box ?? []), ...(c.lines ?? [])].map((l) => l.trim()).filter(Boolean);
        for (const l of ls) {
          if (/^\*/.test(l) && l.length > 12 && l.length < 160 && objectives.length < 40)
            objectives.push(l.replace(/^\*+/, "").trim());
        }
        if (ci === r.length - 1 && r.length >= 3) {
          const first = ls[0];
          if (first && first.length > 40 && contentFirsts.length < 12) contentFirsts.push(first);
        }
      });
    }
  }
  return {
    source: "تطوير استخلاصي من وثيقة الأستاذ نفسها (الأهداف والمحتوى حرفيًا) + إطارات منهجية من ديداكتيك المادة",
    diagnostic: [
      `استحضار المكتسبات السابقة: ماذا تتذكر(ين) من المجزوءة السابقة المرتبطة بموضوع «${slotTitle}»؟`,
      "التموضع الزمني والمكاني: وطّن(ي) موضوع الدرس في الزمان والمكان اعتمادًا على مكتسباتك السابقة.",
    ],
    marhali: objectives.slice(0, 3),
    final: objectives.slice(3, 6),
    produit: contentFirsts.slice(0, 4),
    extension: [
      "لخّص(ي) المضمون الأساسي للدرس في دفترك وفق البنية المعتمدة في القسم.",
      "تحضير الدرس الموالي من كتاب منار (الوحدة الموالية من المجزوءة نفسها).",
    ],
  };
}

export function devPlanFor(slotId: string, f: ImportedFiche, slotTitle: string): DevPlan {
  return DEV_AUTHORED[slotId] ?? buildDevPlan(f, slotTitle);
}
