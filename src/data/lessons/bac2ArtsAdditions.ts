import type { LessonContent, Subject } from "../../types";

function makeContent(id: string, title: string, subject: Subject, focus: string, concepts: string[]): LessonContent {
  const intro = subject === "history"
    ? `يعالج هذا الملف درس «${title}» ضمن تحولات العالم المعاصر، مع التركيز على الإطار الزمني والمجالي والعوامل والنتائج.`
    : `يعالج هذا الملف درس «${title}» ضمن تنظيم المجال العالمي، من خلال المفاهيم والفاعلين والمظاهر والتحديات المرتبطة بالظاهرة.`;
  return {
    id,
    title,
    duration: "حصتان دراسيتان",
    objectives: [
      `ضبط مفهوم وإطار درس «${title}»`,
      "تحليل وثائق الكتاب واستخراج المعطيات الأساسية",
      "ترتيب الأفكار في محاور وتفسير العلاقات بينها",
      "تركيب جواب منظم يوظف المفاهيم والأمثلة",
    ],
    intro,
    coreQuestion: `ما مظاهر «${title}»؟ وما عواملها ونتائجها وتحدياتها؟`,
    sections: [
      {
        title: "التمهيد الإشكالي وبناء المفاهيم",
        blocks: [
          { type: "p", text: intro },
          { type: "callout", tone: "def", label: "المفهوم المركزي", text: `${focus} أستخرج التعريفات والمفاهيم الأساسية من صفحات الكتاب وأربطها بالإشكالية.` },
        ],
      },
      {
        title: "المظاهر والعوامل والنتائج",
        blocks: [
          { type: "ul", title: "خطوات الاشتغال", items: ["أحدد نوع كل وثيقة ومصدرها ومجالها.", "أصف المعطيات وأرتبها في محاور.", "أفسر الظاهرة بالعوامل المناسبة.", "أستخلص النتائج وأقترح خلاصة تركيبية."] },
          { type: "table", head: ["المحور", "ما أستخرجه من صفحات الكتاب"], rows: [["المظاهر", focus], ["العوامل", "عوامل تاريخية أو اقتصادية أو سياسية أو مجالية بحسب موضوع الدرس."], ["النتائج والتحديات", "انعكاسات الظاهرة على الإنسان والمجال، مع أمثلة وأرقام من الوثائق."]] },
        ],
      },
    ],
    glossary: concepts.map((term) => ({ term, def: `مفهوم مفتاحي لفهم درس «${title}» وتوظيفه في تحليل الوثائق والجواب.` })),
    timeline: subject === "history" ? [{ date: "القرن 20م", event: `الإطار العام لدرس «${title}»` }] : [],
    summary: [intro, "تتدرج الإجابة من التعريف والوصف إلى التفسير والتركيب، مع الاستناد إلى وثائق الكتاب.", `أوظف مفاهيم ${concepts.join("، ")} في خلاصة تجيب عن الإشكالية.`],
    examTips: ["أطرح الإشكالية بعد التأطير الزمني أو المجالي.", "أميز بين المظهر والعامل والنتيجة، ولا أخلط الوصف بالتفسير.", "أوظف مثالًا أو رقمًا من وثائق الكتاب في كل محور.", "أختم بخلاصة مركزة وأفق مناسب."],
    quiz: [
      { q: `ما أول خطوة في تحليل درس «${title}»؟`, options: ["تحديد الإطار والإشكالية", "حفظ الخلاصة دون وثائق", "إهمال مصدر الوثيقة", "كتابة النتائج قبل الوصف"], answer: 0, why: "التأطير وطرح الإشكالية يوجهان قراءة الوثائق وبناء الجواب." },
      { q: "ما المسار المنهجي السليم؟", options: ["وصف ثم تفسير ثم تركيب", "تركيب ثم وصف", "حفظ الأرقام فقط", "ذكر النتائج دون أدلة"], answer: 0, why: "ينتقل الجواب من ملاحظة المعطيات إلى تفسيرها ثم تركيب خلاصتها." },
    ],
  };
}

