/** هل يتوفر محتوى للدرس بالمفتاح المعطى؟ */
export function hasLessonContent(key: string): boolean {
  return Boolean(getLessonContent(key));
}

export function getLessonContent(key: string): LessonContent | undefined {
  const direct = LESSON_CONTENT[key];
  if (direct) return direct;
  const alias = ALIASES[key];
  if (!alias) return undefined;
  const base = LESSON_CONTENT[alias.key];
  if (!base) return undefined;
  return alias.title ? { ...base, id: key, title: alias.title } : { ...base, id: key };
}

/** توليد مفتاح الدرس من موقعه في بنية المقرر */
export function lessonKey(branchId: string, subjectId: string, unitIdx: number, lessonIdx: number): string {
  return `${branchId}.${subjectId}.${unitIdx}.${lessonIdx}`;
}

export interface ResolvedLesson {
  content: LessonContent;
  level: CurriculumLevel;
  branch: CurriculumBranch;
  subjectLabel: string;
  unit: CurriculumUnit;
}

/** استخراج الدرس ومساره الكامل من مفتاحه */
export function resolveLesson(key: string): ResolvedLesson | undefined {
  const content = getLessonContent(key);
  if (!content) return undefined;
  const [branchId, subjectId, unitIdx] = key.split(".");
  const level = LEVELS.find((lv) => lv.branches.some((b) => b.id === branchId));
  const branch = level?.branches.find((b) => b.id === branchId);
  const subjectLabel = branch?.subjects.find((s) => s.id === subjectId)?.label ?? "";
  const unit = branch?.units[subjectId]?.[Number(unitIdx)];
  if (!level || !branch || !unit) return undefined;
  return { content, level, branch, subjectLabel, unit };
}
